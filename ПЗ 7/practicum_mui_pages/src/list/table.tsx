type tCar = {
  id?: number;
  "Производитель": string;
  "Название": string;
  "Страна": string;
  "Тип": string;
  "Год": number;
  "Максимальная скорость": number;
};

export type tGroup = {
  id: number;
  "Группа": string | number;
  "Минимальная скорость": number;
  "Максимальная скорость": number;
  "Средняя скорость": number;
}[];

export const getGroupedData = (data: tCar[], groupKey: "Страна" | "Тип" | "Год"): tGroup => {
  const map = new Map<string | number, number[]>();

  data.forEach((car) => {
    const groupValue = car[groupKey];
    const speed = car["Максимальная скорость"];

    if (!map.has(groupValue)) {
      map.set(groupValue, []);
    }

    map.get(groupValue)!.push(speed);
  });

  return Array.from(map.entries())
    .sort(([a], [b]) => String(a).localeCompare(String(b), "ru", { numeric: true }))
    .map(([groupValue, speeds], index) => ({
      id: index + 1,
      "Группа": groupValue,
      "Минимальная скорость": Math.min(...speeds),
      "Максимальная скорость": Math.max(...speeds),
      "Средняя скорость": Math.round(
        speeds.reduce((sum, speed) => sum + speed, 0) / speeds.length
      ),
    }));
};

